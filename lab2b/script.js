// Находим элементы HTML и сохраняем ссылки на них в переменных.
// const запрещает присвоить переменной другую ссылку, но свойства элемента менять можно.
// getElementById ищет по id (без #), querySelector — по CSS-селектору (например, .strength).
// Поле, из которого будем читать введённый пароль.
const passwordInput = document.getElementById('password');
// Абзац для текстовой оценки надёжности.
const result = document.getElementById('result');
// Полоса, показывающая количество выполненных условий.
const meter = document.getElementById('strength-meter');
// Общий блок результата: смена его класса меняет цвет полосы через CSS.
const strength = document.querySelector('.strength');
// Флажок показа и скрытия пароля.
const showPassword = document.getElementById('show-password');

// Эта функция заново проверяет пароль и обновляет страницу при каждом изменении ввода.
function checkPassword() {
  // value содержит текущий текст поля. Ничего не обрезаем и не меняем в пароле.
  const password = passwordInput.value;

  // Проверяем пять условий. Буквы могут быть латинскими или кириллическими.
  // Объект хранит результаты: true — условие выполнено, false — не выполнено.
  // Имена свойств совпадают с id пунктов списка в index.html.
  // Запись /.../ — регулярное выражение (шаблон поиска); test возвращает true или false.
  // Флаг u включает режим Unicode, необходимый для категорий символов вида \p{...}.
  const checks = {
    // Разворачиваем строку в массив кодовых точек Unicode и считаем их.
    // Например, простой эмодзи 😀 здесь считается за один, хотя обычная .length даёт 2.
    // Составные эмодзи могут включать несколько кодовых точек.
    length: [...password].length >= 8,
    // Lu — заглавные буквы Unicode, в том числе A–Z и А–Я, Ё.
    uppercase: /\p{Lu}/u.test(password),
    // Ll — строчные буквы Unicode, в том числе a–z и а–я, ё.
    lowercase: /\p{Ll}/u.test(password),
    // Достаточно хотя бы одной цифры от 0 до 9.
    digit: /[0-9]/.test(password),
    // P — знаки пунктуации, S — символы вроде валют и математических знаков.
    // Пробел не относится ни к одной из этих категорий и не засчитывается.
    special: /[\p{P}\p{S}]/u.test(password)
  };

  // let используем для счётчика, потому что его значение будет изменяться.
  let score = 0;
  // Перебираем названия всех пяти условий.
  for (const name in checks) {
    // Получаем результат текущей проверки по её имени.
    const passed = checks[name];
    // Находим соответствующий пункт списка на странице.
    const item = document.getElementById(name);
    // При true добавляем класс passed, при false удаляем его. CSS задаёт зелёный цвет.
    item.classList.toggle('passed', passed);
    // Условие ? значение_при_true : значение_при_false — короткая запись выбора.
    // textContent меняет только текст: показываем галочку или пустой кружок.
    item.querySelector('.mark').textContent = passed ? '✓' : '○';
    // За выполненное условие добавляем один балл; ++ увеличивает число на единицу.
    if (passed) score++;
  }

  // Надёжный — выполнены все условия; средний — 3–4; слабый — 0–2.
  // Начальное состояние для пустого поля: без цветного класса и с подсказкой.
  let level = '';
  let message = 'Введите пароль';
  // Оценку выводим только для непустого пароля.
  if (password.length > 0) {
    // Строгое равенство ===: надёжным считаем пароль только при всех пяти баллах.
    if (score === 5) {
      level = 'strong';
      message = 'Надёжный пароль';
    } else if (score >= 3) {
      level = 'medium';
      message = 'Средняя надёжность';
    } else {
      level = 'weak';
      message = 'Слабый пароль';
    }
    // Обратные кавычки позволяют вставить значение переменной через ${...}.
    // += дописывает количество выполненных условий к сообщению.
    message += ` · ${score} из 5 условий`;
  }

  // Выводим подготовленную оценку на страницу.
  result.textContent = message;
  // Сохраняем основной класс strength и добавляем класс выбранного уровня.
  strength.className = `strength ${level}`;
  // Числовое значение определяет, какая часть полосы будет заполнена.
  meter.value = score;
  // Текст внутри meter — запасное представление для браузеров без поддержки элемента.
  meter.textContent = `${score} из 5`;
}

// Событие input возникает при вводе, вставке и удалении текста.
// Передаём функцию без скобок: браузер вызовет её сам при наступлении события.
passwordInput.addEventListener('input', checkPassword);
// Событие change срабатывает при переключении флажка.
// () => { ... } — короткая запись функции-обработчика события.
showPassword.addEventListener('change', () => {
  // checked равно true, если флажок установлен. Меняем только видимость, не значение.
  passwordInput.type = showPassword.checked ? 'text' : 'password';
});

// Один раз вызываем проверку при загрузке, чтобы интерфейс соответствовал значению поля.
checkPassword();
